"""Write .claude/commands/<mode>.md for every popular mode in captions/languages.py.

    python3 scripts/make_commands.py

Each command hands its mode to the captions skill (.claude/skills/captions/SKILL.md), which asks for the font
and the editor. Re-run after changing POPULAR; commands for modes no longer listed are removed.
"""
import glob
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from captions import languages  # noqa: E402

DIR = os.path.join(ROOT, ".claude", "commands")
MARK = "<!-- generated by scripts/make_commands.py -->"


def describe(m):
    if m.romanize:
        return "Hinglish captions in the English alphabet"
    if m.name == "hinglish":
        return "Hinglish captions: Hindi and English as spoken, each in its own script"
    if not m.translate_to:
        return f"{m.label} captions"
    first, second = m.label.split(" + ")
    return f"Dual captions: {first} on top, {second} translation underneath"


def main():
    os.makedirs(DIR, exist_ok=True)
    keep = set()
    for name in languages.POPULAR:
        m = languages.parse(name)
        path = os.path.join(DIR, f"{m.name}.md")
        keep.add(path)
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"""---
description: {json.dumps(describe(m) + " for a video, with AssemblyAI. Asks for the font; exports to Final Cut Pro, DaVinci Resolve or Premiere Pro.", ensure_ascii=False)}
argument-hint: [video path or URL]
---
{MARK}
Caption this video in mode `{m.name}` ({describe(m)}): $ARGUMENTS

Use the captions skill (.claude/skills/captions/SKILL.md) and follow every step: ask for the font and the editor
before rendering, transcribe with the API key or the AssemblyAI MCP server, and hand over the editor project.
If no video was given, ask for one.
""")
    for path in glob.glob(os.path.join(DIR, "*.md")):
        if path not in keep and MARK in open(path, encoding="utf-8").read():
            os.remove(path)
    print(f"{len(keep)} commands -> {DIR}")


if __name__ == "__main__":
    main()
